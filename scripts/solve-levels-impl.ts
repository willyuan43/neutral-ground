// Implementation for solve-levels.mjs (TypeScript so it shares the exact model code with the game).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LEVEL1, LEVEL2, solveStormLevel, StormLevelDef, tankStartFor } from '../src/levels/stormLevels';
import type { StormSite } from '../src/model/storm';

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(here, '..', 'public', 'data');
const readJSON = (f: string) => JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8'));

function stormReport(level: StormLevelDef, site: StormSite, storms: any, weather: any) {
  const rain: number[] = storms[level.storm].rainMm;
  const tankStart = tankStartFor(site, weather, storms[level.storm].startLocal);
  const t0 = performance.now();
  const { base, rows } = solveStormLevel(level, site, rain, tankStart);
  const ms = performance.now() - t0;
  const passing = rows.filter((r) => r.pass);
  const lines: string[] = [];
  lines.push(`### Level ${level.id}: ${level.title} (${level.storm})`);
  lines.push(`- Baseline (leave it as is): biggest hour into the drain **${base.peakM3.toFixed(1)} m³** (hour ${base.peakHour + 1}), total to the drain ${base.drainTotal.toFixed(1)} m³.`);
  if (level.tools.tank) lines.push(`- Roof tank level when the storm starts (computed from downtown daily rain since 1 Oct, empty on 1 Oct): ${(['S', 'L'] as const).map((z) => `${z}: keep ${tankStart[z].closed.toFixed(1)} m³, release ${tankStart[z].slow.toFixed(1)} m³`).join('; ')}.`);
  lines.push(`- Layouts tried: ${rows.length} (${(ms / rows.length).toFixed(2)} ms each, ${ms.toFixed(0)} ms total). Max |water-balance error| ${Math.max(...rows.map((r) => Math.abs(r.balance))).toExponential(1)} m³.`);
  lines.push(`- Game targets: biggest hour ≤ **${level.targetPeak} m³**${level.targetKept != null ? `; kept out of the drain ≥ **${level.targetKept} m³**` : ''}${level.budget != null ? `; budget ${level.budget} tokens` : ''}.`);
  lines.push(`- Layouts that pass: **${passing.length}** of ${rows.length}.`);
  const sorted = [...rows].sort((a, b) => a.peak - b.peak);
  lines.push('');
  lines.push('| Layout | Cost | Biggest hour (m³) | Kept out (m³) | Pass |');
  lines.push('|---|---|---|---|---|');
  const show = level.id === 1 ? sorted : [...passing.sort((a, b) => a.cost - b.cost || a.peak - b.peak), ...sorted.filter((r) => !r.pass).slice(0, 6)];
  for (const r of show) lines.push(`| ${r.label} | ${r.cost} | ${r.peak.toFixed(1)} | ${r.kept.toFixed(1)} | ${r.pass ? 'yes' : r.overBudget ? 'over budget' : 'no'} |`);
  return { lines, base, rows, passing };
}

export async function main() {
  const site: StormSite = readJSON('site-storm.json');
  const storms = readJSON('storms.json');
  const weather = readJSON('weather-daily.json');
  const out: string[] = ['## Level calibration (generated by scripts/solve-levels.mjs)', ''];
  const r1 = stormReport(LEVEL1, site, storms, weather);
  out.push(...r1.lines, '');
  // checks for level 1
  const l1pass = r1.passing.map((r) => r.label);
  const smallPass = r1.passing.filter((r) => r.plan.gardens[0]?.size === 'S');
  out.push(`- Check: at least one solution → ${r1.passing.length > 0 ? 'OK' : 'FAIL'}; a small garden can pass (★★) → ${smallPass.length > 0 ? 'OK' : 'FAIL'}; spots off the main flow lines all fail → ${r1.rows.filter((r) => r.pass && !['E', 'F'].includes(r.plan.gardens[0]?.cand ?? '')).length === 0 ? 'OK' : 'FAIL'}.`, '');
  const r2 = stormReport(LEVEL2, site, storms, weather);
  out.push(...r2.lines, '');
  // the obvious move in level 2: level 1's answer (one garden on the main flow line)
  const obvious = r2.rows.filter((r) => r.plan.gardens.length === 1 && ['E', 'F'].includes(r.plan.gardens[0].cand) && !r.plan.tank && !r.plan.disconnect && !r.plan.paving);
  out.push(`- Check: level 1's answer (one garden at E or F, any size) fails level 2 → ${obvious.every((r) => !r.pass) ? 'OK' : 'FAIL'} (biggest hour ${Math.min(...obvious.map((r) => r.peak)).toFixed(1)}–${Math.max(...obvious.map((r) => r.peak)).toFixed(1)} m³).`);
  const fams = new Set(r2.passing.map((r) => r.plan.gardens.map((g) => g.cand).sort().join('') + '|' + (r.plan.tank ? 'T' + r.plan.tank.release : '') + (r.plan.disconnect ? 'D' + r.plan.disconnect : '')));
  out.push(`- Solution families for level 2 (garden spots + tank mode + disconnect): ${fams.size} → ${[...fams].join(', ')}`);
  const strat = new Set(r2.passing.map((r) => r.plan.gardens.map((g) => (['E', 'F'].includes(g.cand) ? 'main line' : g.cand)).sort().join('+') + (r.plan.tank ? ' + tank ' + r.plan.tank.release : '') + (r.plan.disconnect ? ' + disconnect ' + r.plan.disconnect : '')));
  out.push(`- Strategic families (E and F are both on the main flow line): ${strat.size} → ${[...strat].join('; ')}`);
  const every = r2.passing.every((r) => r.plan.gardens.some((g) => g.cand === 'C'));
  out.push(`- Every solution has a garden at C (a smaller stream that still has room at the peak): ${every ? 'yes' : 'no'}.`);
  const cheapest = Math.min(...r2.passing.map((r) => r.cost));
  out.push(`- Cheapest passing cost: ${cheapest} tokens (★★ needs ≤ ${LEVEL2.star3Budget}).`, '');
  const text = out.join('\n');
  fs.writeFileSync(path.join(here, '..', 'scratch-calibration.md'), text);
  console.log(text);
  try { const extra = await import('./solve-level3.ts'); await extra.main(); }
  catch (e) { console.error('Level-3 calibration failed:', e); process.exitCode = 1; }
}
